package com.mthtamim.phonelinkflows

import org.mozilla.javascript.Context
import org.mozilla.javascript.ContextFactory
import org.mozilla.javascript.ScriptableObject

/** API object scripts see as `hub`. Plain methods only — Rhino
 *  reaches them by reflection, so the class is kept in
 *  proguard-rules.pro. No Android Context is exposed to scripts. */
class JsApi(
    private val readVar: (String) -> String,
    private val writeVar: (String, String) -> Unit,
    private val logFn: (String) -> Unit
) {
    fun getVar(name: String): String = try { readVar(name) } catch (_: Exception) { "" }
    fun setVar(name: String, value: String) { try { writeVar(name, value) } catch (_: Exception) { } }
    fun log(text: String) { try { logFn(text) } catch (_: Exception) { } }
}

/** v1.4.7: the `run_js` action — Rhino in interpreter mode
 *  (optimizationLevel -1: the optimizer's generated bytecode
 *  cannot load on ART). Scripts run on the engine's background
 *  thread; a 5 s instruction-count timeout stops runaway
 *  scripts. The result (last expression value) is stored as
 *  variable `js_result` — flows can use it as ${js_result} in
 *  later actions; rules read it via if_var / later scripts. */
object JsRunner {
    private const val TIME_LIMIT_MS = 5000L

    fun run(script: String,
            readVar: (String) -> String,
            writeVar: (String, String) -> Unit,
            log: (String) -> Unit): String {
        if (script.isBlank()) return ""
        val deadline = System.currentTimeMillis() + TIME_LIMIT_MS
        val factory = object : ContextFactory() {
            override fun observeInstructionCount(cx: Context, instructionCount: Int) {
                if (System.currentTimeMillis() > deadline) {
                    throw RuntimeException("JS timeout (5s)")
                }
            }
        }
        return try {
            val result = factory.call { cx ->
                cx.optimizationLevel = -1
                cx.instructionObserverThreshold = 10000
                val scope = cx.initStandardObjects()
                ScriptableObject.putProperty(scope, "hub",
                    Context.javaToJS(JsApi(readVar, writeVar, log), scope))
                val value = cx.evaluateString(scope, script, "run_js", 1, null)
                Context.toString(value)
            } as? String ?: ""
            try { writeVar("js_result", result) } catch (_: Exception) { }
            try { log("JS: " + result.take(120)) } catch (_: Exception) { }
            result
        } catch (e: Exception) {
            try { log("JS ব্যর্থ: " + (e.message ?: "?").take(120)) } catch (_: Exception) { }
            ""
        }
    }
}
